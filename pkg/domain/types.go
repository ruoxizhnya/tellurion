// OrderType represents the type of order.
//
// P1-3 (ODR-016) — LiveEngine 限价单支持:
//   - Market:  市价单, 立即按当前价成交
//   - Limit:   限价单, 仅在价格穿越限价时成交
//   - Stop:    止损/止损买入单, 价格触及 StopPrice 后转为市价单
//   - Trailing: 跟踪止损单, 跟踪市场价 HWM (High Water Mark) 后动态调整
type OrderType string

const (
	OrderTypeMarket   OrderType = "market"
	OrderTypeLimit    OrderType = "limit"
	OrderTypeStop     OrderType = "stop"
	OrderTypeTrailing OrderType = "trailing"
)

// Signal represents a trading signal generated by a strategy
type Signal struct {
	Symbol         string             `json:"symbol"`
	Date           time.Time          `json:"date"`
	Direction      cdom.Direction     `json:"direction"`
	Strength       float64            `json:"strength"`
	CompositeScore float64            `json:"composite_score"`
	Factors        map[string]float64 `json:"factors"`
	Metadata       map[string]any     `json:"metadata"`
	LimitPrice     float64            `json:"limit_price"` // 0 for market orders
	OrderType      OrderType          `json:"order_type"`  // market or limit

	// ─── K17：可选执行算法指定（与 domain.Order 同名字段同语义）────────
	//
	// 策略在信号上请求「这笔意图按 TWAP/VWAP 拆单执行」；零值 = 未指定
	// ⇒ 整单直下（默认路径逐字节不变）。透传链：`tellurion:pkg/strategy` 的 Signal →
	// domain.Signal（convertStrategySignals / toDomainSignals）→
	// domain.Order → `tellurion:pkg/execalgo` 的 Dispatcher。语义见 domain.Order 同名字段。
	ExecAlgo    string    `json:"exec_algo,omitempty"`    // "" / "twap" / "vwap"
	ExecSlices  int       `json:"exec_slices,omitempty"`  // 拆单片数；<=0 按 profile 长度或 1 片
	ExecProfile []float64 `json:"exec_profile,omitempty"` // VWAP 成交量权重（原始量，内部归一化）
}

// Position represents a single position in the portfolio
type Position struct {
	Symbol        string    `json:"symbol"`
	Quantity      float64   `json:"quantity"`
	AvgCost       float64   `json:"avg_cost"`
	CurrentPrice  float64   `json:"current_price"`
	MarketValue   float64   `json:"market_value"`
	UnrealizedPnL float64   `json:"unrealized_pnl"`
	RealizedPnL   float64   `json:"realized_pnl"`
	Weight        float64   `json:"weight"`
	EntryDate     time.Time `json:"entry_date"`
	// T+1 Settlement tracking (A-share rule: shares bought today cannot be sold today)
	BuyDate           time.Time `json:"buy_date"`           // Last buy date for this position
	QuantityToday     float64   `json:"quantity_today"`     // Shares bought today (not yet sellable)
	QuantityYesterday float64   `json:"quantity_yesterday"` // Shares from previous days (sellable today)
	// Metadata is an open extension slot used by risk / strategy
	// modules to persist per-position state. P2-14 take-profit rules
	// use it to track trailing-stop activation / high-water mark /
	// tiered-take-profit current level. Keys are namespaced strings
	// (e.g. "trailing_high", "tiered_current_level").
	Metadata map[string]any `json:"metadata,omitempty"`
}

// Clone 返回 Position 的深拷贝：Metadata 另起一份 map，调用方改返回值
// （包括往里加/删条目）不会影响原持仓，也不会与原持仓的其它读者竞争。
// 除 Metadata 外 Position 全是值字段，普通赋值即可。
func (p Position) Clone() Position {
	out := p
	out.Metadata = maps.Clone(p.Metadata)
	return out
}

// Portfolio represents the current portfolio state
type Portfolio struct {
	Cash        float64             `json:"cash"`
	Positions   map[string]Position `json:"positions"`
	TotalValue  float64             `json:"total_value"`
	DailyReturn float64             `json:"daily_return"`
	UpdatedAt   time.Time           `json:"updated_at"`
}

// RiskMetrics contains portfolio risk measurements
type RiskMetrics struct {
	Volatility      float64   `json:"volatility"`
	Beta            float64   `json:"beta"`
	SharpeRatio     float64   `json:"sharpe_ratio"`
	SortinoRatio    float64   `json:"sortino_ratio"`
	MaxDrawdown     float64   `json:"max_drawdown"`
	MaxDrawdownDate time.Time `json:"max_drawdown_date"`
	VaR95           float64   `json:"var_95"`  // Value at Risk (95%)
	CVaR95          float64   `json:"cvar_95"` // Conditional VaR
}

// Order represents a trading order.
//
// P1-3 (ODR-016) — LiveEngine 限价单: 扩展了 Stop/Trailing 字段.
//   - StopPrice:    触发价 (OrderType=Stop 或 Trailing)
//   - TrailAmount:  跟踪止损绝对偏移 (单位: 元, 与 TrailPercent 互斥, 二者择一)
//   - TrailPercent: 跟踪止损百分比偏移 (0.05 = 5%, 与 TrailAmount 互斥)
//   - HighWaterMark: 跟踪止损运行期 HWM (由 LiveEngine 内部维护, 调用方不应预设)
//
// 限价单 / 止损单 的撮合语义:
//   - Limit Buy:   Ask <= LimitPrice        时成交
//   - Limit Sell:  Bid >= LimitPrice        时成交
//   - Stop Buy:    Ask >= StopPrice         时按市价成交 (突破追涨)
//   - Stop Sell:   Bid <= StopPrice         时按市价成交 (破位止损)
//   - Trailing Buy:  HWM 上升且 (HWM - TrailOffset) 触发后转市价单
//   - Trailing Sell: HWM 上升且 (HWM - TrailOffset) 触发后转市价单 (回撤到位止损)
type Order struct {
	ID         string         `json:"id"`
	Symbol     string         `json:"symbol"`
	Direction  cdom.Direction `json:"direction"` // long or short
	OrderType  OrderType      `json:"order_type"`
	Quantity   float64        `json:"quantity"`
	LimitPrice float64        `json:"limit_price"` // 0 for market orders

	// ─── K17：可选执行算法指定（exec-algo 接线，TASKS.md K17）────────
	//
	// 三个字段全部**可选**，零值 = 未指定 ⇒ 整单直下，默认路径行为与
	// 数值逐字节不变（K17 硬约束，回归腿钉住）。指定后由 `tellurion:pkg/execalgo`
	// 的 TWAP/VWAP 在「送撮合前」拆单：回测侧 `tellurion:pkg/backtest/exec_algo.go`、
	// paper 侧 `tellurion:pkg/trading/paper_exec_algo.go`。子单走同一 CostModel（含
	// impact）——大单拆细后单笔冲击下降，即 D5「模拟真实大单」的效果。
	//
	// ExecAlgo 仅接受 "twap" / "vwap"（未知值 fail-loud）；真实券商
	// 算法单不做（D1）。
	ExecAlgo string `json:"exec_algo,omitempty"` // "" / "twap" / "vwap"
	// ExecSlices 是拆单片数；<=0 时 VWAP 取 len(ExecProfile)，再不行 1 片。
	ExecSlices int `json:"exec_slices,omitempty"`
	// ExecProfile 是 VWAP 的成交量权重（原始量即可，算法内部归一化）；
	//  TWAP 忽略。非法 profile 由算法退化为等分并置 Degraded 标记。
	ExecProfile []float64 `json:"exec_profile,omitempty"`

	// P1-3 扩展字段
	StopPrice     float64   `json:"stop_price,omitempty"`      // 触发价
	TrailAmount   float64   `json:"trail_amount,omitempty"`    // 跟踪绝对偏移
	TrailPercent  float64   `json:"trail_percent,omitempty"`   // 跟踪百分比偏移
	HighWaterMark float64   `json:"high_water_mark,omitempty"` // 跟踪止损 HWM (内部维护)
	Timestamp     time.Time `json:"timestamp"`
	FilledQty     float64   `json:"filled_qty"`
	FillPrice     float64   `json:"fill_price"`
	Status        string    `json:"status"` // "filled" / "partial" / "cancelled" / "expired"
	Notes         string    `json:"notes"`
}

// Clone 返回 Order 的深拷贝：ExecProfile 另起一份切片，调用方改返回值
// （包括改写/扩容 ExecProfile）不会影响原订单。其余字段都是值类型。
func (o Order) Clone() Order {
	out := o
	out.ExecProfile = slices.Clone(o.ExecProfile)
	return out
}

// TargetPosition tracks the target vs actual position for execution gap management.
type TargetPosition struct {
	Symbol      string    `json:"symbol"`
	TargetQty   float64   `json:"target_qty"`  // desired quantity from strategy signal
	ActualQty   float64   `json:"actual_qty"`  // what was actually executed
	PendingQty  float64   `json:"pending_qty"` // quantity not yet filled
	LastUpdated time.Time `json:"last_updated"`
}

// RiskManager defines the interface for risk management
type RiskManager interface {
	CalculatePosition(ctx context.Context, signal Signal, portfolio *Portfolio, regime *cdom.MarketRegime, currentPrice float64, ohlcv []OHLCV) (PositionSize, error)
	DetectRegime(ctx context.Context, ohlcv []OHLCV) (*cdom.MarketRegime, error)
	CheckStopLoss(ctx context.Context, positions []Position, prices map[string]float64) ([]StopLossEvent, error)
}

// PositionSize contains the calculated position size
type PositionSize struct {
	Size       float64 `json:"size"`
	Weight     float64 `json:"weight"`
	StopLoss   float64 `json:"stop_loss"`
	TakeProfit float64 `json:"take_profit"`
	RiskScore  float64 `json:"risk_score"`
}

// StopLossEvent represents a stop loss trigger event
type StopLossEvent struct {
	Symbol   string  `json:"symbol"`
	Type     string  `json:"type"` // "stop_loss" or "take_profit"
	Price    float64 `json:"price"`
	Quantity float64 `json:"quantity"`
	Reason   string  `json:"reason"`
}
